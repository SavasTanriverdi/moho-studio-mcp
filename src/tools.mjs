function formatToolTitle(name) {
  return name
    .split("_")
    .map((part) => part.replace(/([a-z0-9])([A-Z])/g, "$1 $2"))
    .join(" ")
    .replace(/\b\w/g, (ch) => ch.toUpperCase())
    .replace(/\bGltf\b/g, "glTF")
    .replace(/\bFbf\b/g, "FBF")
    .replace(/\bCli\b/g, "CLI")
    .replace(/\bApi\b/g, "API");
}

